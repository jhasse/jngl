/// jngl-shaderc: compiles ShaderPrograms' GLSL at build time for the Vulkan (SPIR-V) or the
/// Direct3D 12 (DXBC) renderer, into a header with a jngl::ShaderBytecode for each.
///
/// Usage:
///   jngl-shaderc spirv|dxbc <output.hpp> <namespace> <name>=[<vertex>,]<fragment>...
///   jngl-shaderc spirv|dxbc <output.hpp> --builtin
///
/// Without a vertex shader, a program uses Sprite::vertexShader(). --builtin compiles JNGL's own
/// shaders, see BuiltinShaders.hpp, into jngl::builtin_bytecode.
/// @file

#include "../BuiltinShaders.hpp"
#include "../spirv/ShaderCompiler.hpp"
#ifdef JNGL_SHADERC_DXBC
#include "../d3d12/HlslCompiler.hpp"
#endif

#include <cstdint>
#include <cstdio>
#include <exception>
#include <fstream>
#include <map>
#include <span>
#include <sstream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

namespace {

struct ProgramSource {
	std::string name;
	/// Where the GLSL is from, for the error messages
	std::string vertexOrigin;
	std::string vertex;
	std::string fragmentOrigin;
	std::string fragment;
};

std::string readFile(const std::string& path) {
	std::ifstream file(path, std::ios::binary);
	if (!file) {
		throw std::runtime_error("Couldn't read " + path);
	}
	std::ostringstream buffer;
	buffer << file.rdbuf();
	return buffer.str();
}

/// Parses <name>=[<vertex>,]<fragment>
ProgramSource parseProgram(const std::string_view argument) {
	const auto equals = argument.find('=');
	if (equals == std::string_view::npos || equals == 0) {
		throw std::runtime_error("Expected <name>=[<vertex>,]<fragment>, not " +
		                         std::string(argument));
	}
	ProgramSource program;
	program.name = argument.substr(0, equals);
	const std::string_view files = argument.substr(equals + 1);
	if (const auto comma = files.find(','); comma == std::string_view::npos) {
		program.vertexOrigin = "Sprite::vertexShader()";
		program.vertex = jngl::builtin_shaders::texturedVertex;
		program.fragmentOrigin = files;
	} else {
		program.vertexOrigin = files.substr(0, comma);
		program.vertex = readFile(program.vertexOrigin);
		program.fragmentOrigin = files.substr(comma + 1);
	}
	program.fragment = readFile(program.fragmentOrigin);
	return program;
}

#ifdef JNGL_SHADERC_DXBC
/// DXBC as 32-bit words, as its size is a multiple of 4, like SPIR-V
std::vector<uint32_t> toWords(const std::span<const uint8_t> bytes) {
	if (bytes.size() % 4 != 0) {
		throw std::runtime_error("The size of the bytecode isn't a multiple of 4.");
	}
	std::vector<uint32_t> words(bytes.size() / 4);
	for (size_t i = 0; i < words.size(); ++i) {
		words[i] = uint32_t{ bytes[i * 4] } | uint32_t{ bytes[i * 4 + 1] } << 8 |
		           uint32_t{ bytes[i * 4 + 2] } << 16 | uint32_t{ bytes[i * 4 + 3] } << 24;
	}
	return words;
}
#endif

void writeArray(std::ostream& out, const std::string& name, const std::vector<uint32_t>& words) {
	out << "inline constexpr std::array<uint32_t, " << words.size() << "> " << name << " = {";
	for (size_t i = 0; i < words.size(); ++i) {
		out << (i % 8 == 0 ? "\n\t" : " ");
		char word[16];
		std::snprintf(word, sizeof(word), "0x%08xu,", words[i]);
		out << word;
	}
	out << "\n};\n\n";
}

/// The header with a jngl::ShaderBytecode for each of \a programs in namespace \a space
std::string compile(const std::vector<ProgramSource>& programs, const std::string& space,
                    const bool dxbc) {
	std::ostringstream out;
	out << "// Generated by jngl-shaderc; do not edit.\n"
	       "#pragma once\n\n"
	       "#include <jngl/ShaderBytecode.hpp>\n\n"
	       "#include <array>\n"
	       "#include <cstdint>\n\n"
	       "/// Compiled to "
	    << (dxbc ? "DXBC for the Direct3D 12" : "SPIR-V for the Vulkan")
	    << " renderer, see jngl::ShaderProgram(const jngl::ShaderBytecode&)\n"
	       "namespace "
	    << space << " {\n\n";
	// Identical vertex shaders, typically Sprite::vertexShader(), are only written once
	std::map<std::vector<uint32_t>, std::string> vertexArrays;
	for (const ProgramSource& program : programs) {
		jngl::CompiledProgram compiled;
		try {
			compiled = jngl::compileGlslProgram(program.vertex.c_str(), program.fragment.c_str());
		} catch (const std::exception& e) {
			throw std::runtime_error(program.vertexOrigin + " and " + program.fragmentOrigin +
			                         ": " + e.what());
		}
		std::vector<uint32_t> vertex = compiled.vertexSpirv;
		std::vector<uint32_t> fragment = compiled.fragmentSpirv;
#ifdef JNGL_SHADERC_DXBC
		if (dxbc) {
			vertex = toWords(jngl::compileSpirvToDxbc(vertex, jngl::Shader::Type::VERTEX,
			                                          program.vertexOrigin.c_str()));
			fragment = toWords(jngl::compileSpirvToDxbc(fragment, jngl::Shader::Type::FRAGMENT,
			                                            program.fragmentOrigin.c_str()));
		}
#endif
		const std::string& name = program.name;
		// Its bytecode also depends on the layout of the fragment shader's uniforms
		const auto [vertexArray, isNew] = vertexArrays.try_emplace(vertex, name + "Vertex");
		if (isNew) {
			writeArray(out, vertexArray->second, vertex);
		}
		writeArray(out, name + "Fragment", fragment);
		out << "inline constexpr std::array<jngl::ShaderBytecode::Uniform, "
		    << compiled.uniforms.size() << "> " << name << "Uniforms = { {\n";
		for (const jngl::ShaderUniform& uniform : compiled.uniforms) {
			out << "\t{ \"" << uniform.name << "\", " << uniform.offset << ", " << uniform.size
			    << " },\n";
		}
		out << "} };\n\n"
		    << "inline constexpr jngl::ShaderBytecode " << name << "{ " << vertexArray->second
		    << ", " << name << "Fragment, " << name << "Uniforms, " << compiled.uniformBlockSize
		    << ", " << (compiled.pushConstants ? "true" : "false") << " };\n\n";
	}
	out << "} // namespace " << space << "\n";
	return out.str();
}

} // namespace

int main(const int argc, const char* const* const argv) {
	const std::vector<std::string_view> args(argv, argv + argc);
	if (args.size() < 4 || (args[1] != "spirv" && args[1] != "dxbc")) {
		std::fprintf(stderr,
		             "Usage: %s spirv|dxbc <output.hpp> <namespace> "
		             "<name>=[<vertex>,]<fragment>...\n"
		             "       %s spirv|dxbc <output.hpp> --builtin\n",
		             argv[0], argv[0]);
		return 1;
	}
	const bool dxbc = args[1] == "dxbc";
#ifndef JNGL_SHADERC_DXBC
	if (dxbc) {
		std::fprintf(stderr, "This jngl-shaderc has been built without DXBC support.\n");
		return 1;
	}
#endif
	std::string header;
	try {
		if (args[3] == "--builtin") {
			using namespace jngl::builtin_shaders;
			const auto builtin = [](const char* name, const char* vertex, const char* fragment) {
				return ProgramSource{ name, name, vertex, name, fragment };
			};
			header = compile(
			    {
			        builtin("colored", coloredVertex, coloredFragment),
			        builtin("rounded", roundedVertex, roundedFragment),
			        builtin("textured", texturedVertex, texturedFragment),
			        builtin("video", texturedVertex, videoFragment),
			    },
			    "jngl::builtin_bytecode", dxbc);
		} else {
			std::vector<ProgramSource> programs;
			for (size_t i = 4; i < args.size(); ++i) {
				programs.push_back(parseProgram(args[i]));
			}
			header = compile(programs, std::string(args[3]), dxbc);
		}
	} catch (const std::exception& e) {
		std::fprintf(stderr, "jngl-shaderc: %s\n", e.what());
		return 1;
	}
	std::ofstream file(std::string(args[2]), std::ios::binary);
	file << header;
	if (!file) {
		std::fprintf(stderr, "jngl-shaderc: couldn't write %s\n", argv[2]);
		return 1;
	}
	return 0;
}
