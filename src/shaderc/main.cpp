/// jngl-shaderc: compiles JNGL's built-in shaders (see BuiltinShaders.hpp) at build time for the
/// Vulkan or the Direct3D 12 backend, the same way games' shaders are compiled at runtime.
///
/// Usage: jngl-shaderc spirv|dxbc <output.hpp>
///
/// Writes a header with each program's bytecode and the layout of its uniforms, see
/// jngl::builtin_bytecode::Program.
/// @file

#include "../BuiltinShaders.hpp"
#include "../spirv/ShaderCompiler.hpp"
#ifdef JNGL_SHADERC_DXBC
#include "../d3d12/HlslCompiler.hpp"
#endif

#include <cstdint>
#include <cstdio>
#include <exception>
#include <fstream>
#include <span>
#include <sstream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

namespace {

struct BuiltinProgram {
	const char* name;
	const char* vertex;
	const char* fragment;
};

#ifdef JNGL_SHADERC_DXBC
/// DXBC as 32-bit words, as its size is a multiple of 4, like SPIR-V
std::vector<uint32_t> toWords(const std::span<const uint8_t> bytes) {
	if (bytes.size() % 4 != 0) {
		throw std::runtime_error("The size of the bytecode isn't a multiple of 4.");
	}
	std::vector<uint32_t> words(bytes.size() / 4);
	for (size_t i = 0; i < words.size(); ++i) {
		words[i] = uint32_t{ bytes[i * 4] } | uint32_t{ bytes[i * 4 + 1] } << 8 |
		           uint32_t{ bytes[i * 4 + 2] } << 16 | uint32_t{ bytes[i * 4 + 3] } << 24;
	}
	return words;
}
#endif

void writeArray(std::ostream& out, const std::string& name, const std::vector<uint32_t>& words) {
	out << "inline constexpr std::array<uint32_t, " << words.size() << "> " << name << " = {";
	for (size_t i = 0; i < words.size(); ++i) {
		out << (i % 8 == 0 ? "\n\t" : " ");
		char word[16];
		std::snprintf(word, sizeof(word), "0x%08xu,", words[i]);
		out << word;
	}
	out << "\n};\n\n";
}

} // namespace

int main(const int argc, const char* const* const argv) {
	if (argc != 3 ||
	    (std::string_view(argv[1]) != "spirv" && std::string_view(argv[1]) != "dxbc")) {
		std::fprintf(stderr, "Usage: %s spirv|dxbc <output.hpp>\n", argc > 0 ? argv[0] : "");
		return 1;
	}
	const bool dxbc = std::string_view(argv[1]) == "dxbc";
#ifndef JNGL_SHADERC_DXBC
	if (dxbc) {
		std::fprintf(stderr, "This jngl-shaderc has been built without DXBC support.\n");
		return 1;
	}
#endif
	using namespace jngl::builtin_shaders;
	const std::vector<BuiltinProgram> programs = {
		{ "colored", coloredVertex, coloredFragment },
		{ "rounded", roundedVertex, roundedFragment },
		{ "textured", texturedVertex, texturedFragment },
	};

	std::ostringstream out;
	out << "// Generated by jngl-shaderc from BuiltinShaders.hpp; do not edit.\n"
	       "#pragma once\n\n"
	       "#include <array>\n"
	       "#include <cstdint>\n"
	       "#include <span>\n"
	       "#include <string_view>\n\n"
	       "namespace jngl::builtin_bytecode {\n\n"
	       "/// One of a Program's uniforms, see jngl::ShaderUniform\n"
	       "struct Uniform {\n"
	       "\tstd::string_view name;\n"
	       "\tuint32_t offset;\n"
	       "\tuint32_t size;\n"
	       "};\n\n"
	       "/// A built-in shader program, see jngl::CompiledProgram\n"
	       "struct Program {\n"
	       "\t/// "
	    << (dxbc ? "DXBC" : "SPIR-V")
	    << ", as 32-bit words\n"
	       "\tstd::span<const uint32_t> vertex;\n"
	       "\tstd::span<const uint32_t> fragment;\n"
	       "\tstd::span<const Uniform> uniforms;\n"
	       "\tuint32_t uniformBlockSize;\n"
	       "\tbool pushConstants;\n"
	       "};\n\n";
	try {
		for (const BuiltinProgram& program : programs) {
			const jngl::CompiledProgram compiled =
			    jngl::compileGlslProgram(program.vertex, program.fragment);
			std::vector<uint32_t> vertex = compiled.vertexSpirv;
			std::vector<uint32_t> fragment = compiled.fragmentSpirv;
#ifdef JNGL_SHADERC_DXBC
			if (dxbc) {
				vertex = toWords(
				    jngl::compileSpirvToDxbc(vertex, jngl::Shader::Type::VERTEX, program.name));
				fragment = toWords(
				    jngl::compileSpirvToDxbc(fragment, jngl::Shader::Type::FRAGMENT, program.name));
			}
#endif
			const std::string name = program.name;
			writeArray(out, name + "Vertex", vertex);
			writeArray(out, name + "Fragment", fragment);
			out << "inline constexpr std::array<Uniform, " << compiled.uniforms.size() << "> "
			    << name << "Uniforms = { {\n";
			for (const jngl::ShaderUniform& uniform : compiled.uniforms) {
				out << "\t{ \"" << uniform.name << "\", " << uniform.offset << ", " << uniform.size
				    << " },\n";
			}
			out << "} };\n\n"
			    << "inline constexpr Program " << name << "{ " << name << "Vertex, " << name
			    << "Fragment, " << name << "Uniforms, " << compiled.uniformBlockSize << ", "
			    << (compiled.pushConstants ? "true" : "false") << " };\n\n";
		}
	} catch (const std::exception& e) {
		std::fprintf(stderr, "jngl-shaderc: %s\n", e.what());
		return 1;
	}
	out << "} // namespace jngl::builtin_bytecode\n";

	std::ofstream file(argv[2], std::ios::binary);
	file << out.str();
	if (!file) {
		std::fprintf(stderr, "jngl-shaderc: couldn't write %s\n", argv[2]);
		return 1;
	}
	return 0;
}
